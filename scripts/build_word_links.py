# Additional explicitly reviewed links used in holiday boards.
PATHS += '\nTAG TEAM WORK\nMARCH PAST LIFE\n'


def build():
    edges = set()
    for line in PATHS.splitlines():
        words = line.split()
        edges.update(zip(words, words[1:]))
    graph = defaultdict(list)
    for a, b in sorted(edges):
        graph[a].append(b)
    candidates = []
    def walk(path):
        if len(path) == 7:
            candidates.append(tuple(path))
            return
        for word in graph[path[-1]]:
            if word not in path:
                walk(path + [word])
    for word in sorted(graph):
        walk([word])
    candidates.sort(key=lambda c: hashlib.sha256(' '.join(c).encode()).digest())
    chosen, starts, uses = [], Counter(), Counter()
    # Prefer diverse starting words and links, not 200 minor edits of one chain.
    for cap in (1, 2, 3, 4):
        for chain in candidates:
            pairs = list(zip(chain, chain[1:]))
            if chain in chosen or starts[chain[0]] >= cap:
                continue
            if any(len(set(pairs) & set(zip(old, old[1:]))) > 3 for old in chosen):
                continue
            if any(uses[p] >= 14 for p in pairs):
                continue
            chosen.append(chain)
            starts[chain[0]] += 1
            uses.update(pairs)
            if len(chosen) == 220:
                break
        if len(chosen) == 220:
            break
    assert len(chosen) == 220, len(chosen)
    for _, chain in HOLIDAYS.values():
        words = chain.split()
        assert len(words) == 7
        assert all(pair in edges for pair in zip(words, words[1:])), chain
    result = {'boards': [list(c) for c in chosen],
              'holidays': {key: {'theme': theme, 'words': chain.split()} for key, (theme, chain) in HOLIDAYS.items()},
              'approved_links': [list(pair) for pair in sorted(edges)]}
    path = Path(__file__).resolve().parents[1] / 'custom_components/daily_puzzle/word_links.json'
    path.write_text(json.dumps(result, indent=2) + '\n')
    print(f'{len(chosen)} boards; {len(starts)} starting words; {len(edges)} approved links; {len(HOLIDAYS)} holidays')

if __name__ == '__main__':
    build()
